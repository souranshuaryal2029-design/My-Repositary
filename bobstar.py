import turtle
turtle.Screen().bgcolor("red")
bob = turtle.Turtle()
bob.forward(100)
bob.left(120)
bob.forward(100)
bob.left(120)
bob.forward(100)
bob.penup()
bob.right(150)
bob.forward(50)
bob.pendown()
bob.right(90)
bob.forward(100)
bob.right(120)
bob.forward(100)
bob.right(120)
bob.forward(100)
bob.mainloop()
turtle.done()